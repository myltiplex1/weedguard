"""
Safely remove weeds from one maize plot in two calls. CALL 1 (only plot_id): capture image, check quality, detect plants, select safe weed targets, plan weeding, request approval. CALL 2 (plot_id + plan_id + confirmation_code): execute the approved plan.

Generated by Synapse (v2 Custom mode). Edit freely — you own this file.
Run:  python weed_plot_server.py
"""
from __future__ import annotations

from mcp.server.fastmcp import FastMCP
from actuator import execute_weeding_plan
from field import capture_plot_image
from vision import check_image_quality, detect_plants
from safety import select_weed_targets
from planner import plan_weeding, request_operator_confirmation
from planner import plan_weeding
from planner import request_operator_confirmation
from vision import check_image_quality
from vision import detect_plants
mcp = FastMCP("actuator-weed_plot")


@mcp.tool(name="weed_plot", description="Safely remove weeds from one maize plot in two calls. CALL 1 (only plot_id): capture image, check quality, detect plants, select safe weed targets, plan weeding, request approval. CALL 2 (plot_id + plan_id + confirmation_code): execute the approved plan.")
def weed_plot(plot_id: str, plan_id: str, confirmation_code: str) -> dict:
    
    # CALL 2: Execute approved plan
    if plan_id and confirmation_code:
        result = execute_weeding_plan(plan_id, confirmation_code)
        if result.get("ok"):
            return {"status": "done", **result}
        else:
            return {"status": "not_done", **result}

    # Error: confirmation_code given without plan_id
    if confirmation_code and not plan_id:
        return {"status": "error", "message": "confirmation_code requires plan_id"}

    # CALL 1: Capture, analyze, plan
    capture_result = capture_plot_image(plot_id)
    if not capture_result.get("ok"):
        return {
            "status": "error",
            "stage": "camera",
            "message": capture_result.get("message", "Camera capture failed")
        }

    image_path = capture_result.get("image_path")

    quality_result = check_image_quality(image_path)
    if not quality_result.get("ok"):
        return {
            "status": "blocked",
            "stage": "image_quality",
            "problems": quality_result.get("problems", []),
            "message": quality_result.get("message", "Image quality check failed")
        }

    detect_result = detect_plants(image_path)
    if not detect_result.get("ok"):
        return {
            "status": "error",
            "stage": "detection",
            "message": detect_result.get("message", "Plant detection failed")
        }

    scan_id = detect_result.get("scan_id")

    selection_result = select_weed_targets(scan_id)
    if not selection_result.get("ok"):
        return {
            "status": "error",
            "stage": "selection",
            "message": selection_result.get("message", "Weed target selection failed")
        }

    maize_found = selection_result.get("maize_count", 0)
    weeds_found = selection_result.get("weed_count", 0)
    weeds_safe_to_remove = selection_result.get("safe_target_count", 0)
    weeds_skipped_near_maize = selection_result.get("skipped_near_maize", 0)

    if weeds_safe_to_remove == 0:
        return {
            "status": "nothing_to_do",
            "maize_count": maize_found,
            "weed_count": weeds_found,
            "weeds_skipped_near_maize": weeds_skipped_near_maize
        }

    selection_id = selection_result.get("selection_id")

    plan_result = plan_weeding(selection_id)
    if not plan_result.get("ok"):
        return {
            "status": "error",
            "stage": "planning",
            "message": plan_result.get("message", "Weeding plan creation failed")
        }

    new_plan_id = plan_result.get("plan_id")

    confirmation_result = request_operator_confirmation(new_plan_id)
    if not confirmation_result.get("ok"):
        return {
            "status": "error",
            "stage": "confirmation_request",
            "message": confirmation_result.get("message", "Confirmation request failed")
        }

    return {
        "status": "awaiting_approval",
        "plot_id": plot_id,
        "plan_id": new_plan_id,
        "maize_found": maize_found,
        "weeds_found": weeds_found,
        "weeds_safe_to_remove": weeds_safe_to_remove,
        "weeds_skipped_near_maize": weeds_skipped_near_maize,
        "estimated_seconds": plan_result.get("estimated_seconds"),
        "summary": confirmation_result.get("summary"),
        "preview_image": confirmation_result.get("preview_image"),
        "next_step": "Ask the farmer to review the plan. If the farmer agrees, call weed_plot again with plot_id='{}', plan_id='{}', and the 4-digit confirmation_code the farmer reads from the robot operator console.".format(plot_id, new_plan_id)
    }


if __name__ == "__main__":
    mcp.run()
