"""
Safely removes weeds from one maize plot in two calls. CALL 1 (only plot_id): captures image, checks quality, detects plants, selects safe weed targets, plans weeding and requests operator confirmation. CALL 2 (plot_id + plan_id + confirmation_code): executes the approved weeding plan.

Generated by Synapse (v2 Custom mode). Edit freely — you own this file.
Run:  python weed_plot_server.py
"""
from __future__ import annotations

from mcp.server.fastmcp import FastMCP
from actuator import execute_weeding_plan
from field import capture_plot_image
from vision import check_image_quality
from vision import detect_plants
from safety import select_weed_targets
from planner import plan_weeding
from planner import request_operator_confirmation
mcp = FastMCP("actuator-weed_plot")


@mcp.tool(name="weed_plot", description="Safely removes weeds from one maize plot in two calls. CALL 1 (only plot_id): captures image, checks quality, detects plants, selects safe weed targets, plans weeding and requests operator confirmation. CALL 2 (plot_id + plan_id + confirmation_code): executes the approved weeding plan.")
def weed_plot(plot_id: str, plan_id: str = '', confirmation_code: str = '') -> dict:
    
    # CALL 2: Execute approved weeding plan
    if plan_id and confirmation_code:
        result = execute_weeding_plan(plan_id, confirmation_code)
        if result.get("ok"):
            return {"status": "done", **result}
        else:
            return {"status": "not_done", **result}

    # Error: confirmation_code given without plan_id
    if confirmation_code and not plan_id:
        return {"status": "error", "message": "confirmation_code requires plan_id"}

    # CALL 1: Capture, analyze, plan and request approval
    capture_result = capture_plot_image(plot_id)
    if not capture_result.get("ok"):
        return {
            "status": "error",
            "stage": "camera",
            "error_code": capture_result.get("error_code"),
            "message": capture_result.get("message")
        }

    image_path = capture_result.get("image_path")

    quality_result = check_image_quality(image_path)
    if not quality_result.get("ok"):
        return {
            "status": "blocked",
            "stage": "image_quality",
            "problems": quality_result.get("problems", [])
        }

    detect_result = detect_plants(image_path)
    if not detect_result.get("ok"):
        return {
            "status": "error",
            "stage": "detection",
            "message": detect_result.get("message")
        }

    preview_path = detect_result.get("preview_path")
    scan_id = detect_result.get("scan_id")

    selection_result = select_weed_targets(scan_id)
    if not selection_result.get("ok"):
        return {
            "status": "error",
            "stage": "selection",
            "message": selection_result.get("message")
        }

    maize_count = selection_result.get("maize_count")
    weed_count = selection_result.get("weed_count")
    safe_target_count = selection_result.get("safe_target_count")
    skipped_near_maize = selection_result.get("skipped_near_maize")

    if safe_target_count == 0:
        return {
            "status": "nothing_to_do",
            "maize_count": maize_count,
            "weed_count": weed_count,
            "skipped_near_maize": skipped_near_maize,
            "message": "Every weed is too close to maize"
        }

    selection_id = selection_result.get("selection_id")
    plan_result = plan_weeding(selection_id)
    if not plan_result.get("ok"):
        return {
            "status": "blocked",
            "message": plan_result.get("message")
        }

    plan_id_new = plan_result.get("plan_id")
    estimated_seconds = plan_result.get("estimated_seconds")

    confirmation_request = request_operator_confirmation(plan_id_new)

    return {
        "status": "awaiting_approval",
        "plot_id": plot_id,
        "plan_id": plan_id_new,
        "maize_found": maize_count,
        "weeds_found": weed_count,
        "weeds_safe_to_remove": safe_target_count,
        "weeds_skipped_near_maize": skipped_near_maize,
        "estimated_seconds": estimated_seconds,
        "summary": confirmation_request.get("summary"),
        "preview_image": preview_path,
        "next_step": "Ask the farmer to review the preview and summary. Only if the farmer agrees, call weed_plot again with plot_id, plan_id and the 4-digit confirmation_code the farmer reads from the robot operator console."
    }


if __name__ == "__main__":
    mcp.run()
